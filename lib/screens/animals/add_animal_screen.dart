  Future<void> _submit() async {
    if (!_formKey.currentState!.validate()) return;

    // Validate field selection
    if (_selectedFieldId == null) {
      ScaffoldMessenger.of(context).showSnackBar(
        const SnackBar(
          content: Text('Please select a field before saving.'),
          backgroundColor: Colors.orange,
        ),
      );
      return;
    }

    // Validate animal name
    if (_nameController.text.trim().isEmpty) {
      ScaffoldMessenger.of(context).showSnackBar(
        const SnackBar(
          content: Text('Animal name is required.'),
          backgroundColor: Colors.orange,
        ),
      );
      return;
    }

    // Validate breed "Other" — free text must not be empty
    if (_selectedBreed == _breedOther && _breedController.text.trim().isEmpty) {
      ScaffoldMessenger.of(context).showSnackBar(
        const SnackBar(
          content: Text('Please enter the breed name or select one from the list.'),
          backgroundColor: Colors.orange,
        ),
      );
      return;
    }

    setState(() => _isLoading = true);

    try {
      final animalData = {
        'name': _nameController.text,
        // Use free-text if "Other" selected, otherwise use the dropdown value
        'breed': (_selectedBreed == _breedOther || _selectedBreed == null)
            ? (_breedController.text.trim().isEmpty ? null : _breedController.text.trim())
            : _selectedBreed,
        'animalType': _selectedType,
        'age': _ageInMonths.toInt(),
        'ageYears': (_ageInMonths / 12).floor(),
        'sex': _selectedSex,
        'weight': double.tryParse(_weightController.text),
        // tagNumber is auto-generated by the backend — not sent by the user
        'notes': _notesController.text,
        'fieldId': _selectedFieldId,
        // Derive vaccination status from the checklist — true if any vaccine was checked
        'vaccination': _vaccineSelections.values.any((v) => v['checked'] == true) || _isVaccinated,
        // Fix #3 — ne pas envoyer vaccines dans le payload animal pour éviter
        // le double enregistrement (les vaccins sont créés séparément via VaccineService)
        // 'vaccines': null,
        
        // Financial & Genealogy
        'origin': _selectedOrigin,
        'motherId': _selectedMotherId,
        'fatherId': _selectedFatherId,
        'birthWeightKg': double.tryParse(_birthWeightController.text),
        'birthCost': double.tryParse(_birthCostController.text),
        'purchasePrice': double.tryParse(_purchasePriceController.text),
        // salePrice only relevant in edit mode (set via sell screen, not creation form)
        if (isEditMode) 'salePrice': double.tryParse(_salePriceController.text),

        // COW + female
        'isPregnant': (_selectedType == 'cow' && _selectedSex == 'female') ? _isPregnant : null,
        'lactationNumber': (_selectedType == 'cow' && _selectedSex == 'female')
            ? int.tryParse(_lactationNumberController.text)
            : null,
        'dailyMilkAvgL': (_selectedType == 'cow' && _selectedSex == 'female')
            ? double.tryParse(_dailyMilkAvgController.text)
            : null,
        // HORSE
        'raceCategory': _selectedType == 'horse' ? _raceCategory : null,
        'trainingLevel': _selectedType == 'horse' ? _trainingLevel : null,
        // SHEEP
        'meatGrade': _selectedType == 'sheep' ? _meatGrade : null,
        // DOG
        'dogRole': _selectedType == 'dog' ? _dogRole : null,
      };

      Animal animal;
      if (isEditMode) {
        animal = await _animalService.updateAnimal(widget.animal!.nodeId, animalData);
      } else {
        animal = await _animalService.createAnimal(animalData);
      }

      // ── Upload photo ──
      if (_selectedImage != null || _webImageBytes != null) {
        try {
          if (kIsWeb && _webImageBytes != null) {
            animal = await _animalService.uploadAnimalPhotoBytes(
                animal.nodeId, _webImageBytes!);
          } else if (_selectedImage != null) {
            animal = await _animalService.uploadAnimalPhoto(
                animal.nodeId, _selectedImage!);
          }
        } catch (e) {
          if (mounted) {
            ScaffoldMessenger.of(context).showSnackBar(
              SnackBar(
                content: Text('Warning: Photo upload failed - $e'),
                backgroundColor: Colors.orange,
                duration: const Duration(seconds: 4),
              ),
            );
          }
        }
      }

      // ── Record selected vaccinations ──
      final checkedSelections = _vaccineSelections.entries.where((e) => e.value['checked'] == true).toList();
      for (var entry in checkedSelections) {
        final sel = entry.value;
        try {
          await _vaccineService.createRecord(
            animalId: animal.id,
            vaccineCode: sel['isOther'] == true ? 'OTHER' : entry.key,
            administeredBy: 'Farmer',
            administeredAt: DateTime.parse(sel['date']),
            doseGiven: (sel['dose'] as num).toDouble(),
            notes: sel['isOther'] == true ? sel['name'] : null, // Store name in notes for OTHER
          );
        } catch (ve) {
          // Silently skip failed vaccine records
        }
      }

      // ── Generate Smart Planning ──
      // Fix #5 — ne générer le plan que si aucun vaccin n'a déjà été sélectionné
      // (évite les doublons si l'utilisateur a coché des vaccins à l'étape 3)
      if (!isEditMode && checkedSelections.isEmpty) {
        try {
          await _vaccineService.generateSmartPlan(animal.id);
        } catch (pe) {
          // Silently skip smart plan generation failure
        }
      }

      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(
            content: Text(isEditMode ? 'Animal mis à jour avec succès !' : 'Animal enregistré avec succès ! Plan généré.'),
            backgroundColor: AppColors.success,
          ),
        );

        // ── Afficher le QR code après création (pas en mode édition) ──
        // L'agriculteur peut imprimer ce QR et le coller sur l'animal
        if (!isEditMode) {
          await AnimalQrDialog.show(context, animal);
        }

        Navigator.pop(context, true);
      }
    } catch (e) {
      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(content: Text('Error: ${e.toString()}')),
        );
      }
    } finally {
      if (mounted) setState(() => _isLoading = false);
    }
  }

