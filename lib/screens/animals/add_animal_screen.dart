                              Text(
                                isLastStep
                                  ? (isEditMode ? 'Mettre à jour' : 'Enregistrer l\'animal')
                                  : 'Continuer', 
                                style: const TextStyle(
                                  color: Colors.white,
                                  fontSize: 18,
                                  fontWeight: FontWeight.bold,
