  @override
  void initState() {
    super.initState();
    if (isEditMode) {
      final a = widget.animal!;
      _nameController.text = a.name;
      _breedController.text = a.breed ?? '';
      // tagNumber is read-only — not editable by the user
      _weightController.text = a.weight?.toString() ?? '';
      _notesController.text = a.notes ?? '';
      _selectedType = a.animalType.toLowerCase();
      _selectedSex = a.sex.toLowerCase();
      _ageInMonths = a.age.toDouble();
      _isVaccinated = a.vaccination;
      _existingImageUrl = a.profileImage;

      // Restore breed selection: check if the saved breed is in the list
      if (a.breed != null && a.breed!.isNotEmpty) {
        final breeds = _breedsByType[a.animalType.toLowerCase()] ?? [];
        if (breeds.contains(a.breed)) {
          _selectedBreed = a.breed;
        } else {
          _selectedBreed = _breedOther;
          _breedController.text = a.breed!;
        }
      }

      // Financials
      _selectedOrigin = a.origin;
      _selectedMotherId = a.motherId;
      _selectedFatherId = a.fatherId;
      _birthWeightController.text = a.birthWeightKg?.toString() ?? '';
      _birthCostController.text = a.birthCost?.toString() ?? '';
      _purchasePriceController.text = a.purchasePrice?.toString() ?? '';
      _salePriceController.text = a.salePrice?.toString() ?? '';
      
      // Prefer vaccineRecords for modern sync
      if (a.vaccineRecords != null && a.vaccineRecords!.isNotEmpty) {
        // vaccineRecords are loaded into _vaccineSelections via _fetchRegulations()
      }
      
      _isPregnant = a.isPregnant;
      // Start at step 2 (Details) when editing
      _currentStep = 2;
    }
    _ageMonthsController.text = _ageInMonths.toInt().toString();
    _ageMonthsController.addListener(() {
      final val = double.tryParse(_ageMonthsController.text);
      if (val != null && val >= 1 && val <= 240) {
        setState(() => _ageInMonths = val);
      }
      // Values outside 1-240 are silently ignored — slider enforces the range visually
    });
    _fetchFields();
    _fetchPotentialParents();
  }

  Future<void> _fetchPotentialParents() async {
    try {
      final animals = await _animalService.getAnimals();
      if (mounted) setState(() {
        _potentialParents = animals;
      });
    } catch (_) {
      // Silently fail — parents list is optional
    }
  }

  Future<void> _fetchFields() async {
    try {
      final fields = await _fieldService.getFields();
      setState(() {
        _fields = fields;
        if (!isEditMode && _fields.isNotEmpty) {
          _selectedFieldId = _fields.first.id;
          _fetchRegulations(); // Start fetching for default field
        } else if (isEditMode) {
          _selectedFieldId = widget.animal?.fieldId;
          // Fetch regulations for the animal's field in edit mode
          if (_selectedFieldId != null) {
            _fetchRegulations();
          }
        }
      });
    } catch (_) {
      // Silently fail — fields list is optional
    }
  }

  Future<void> _fetchRegulations() async {
    if (_selectedFieldId == null) return;
    
    setState(() => _isLoadingRegulations = true);
    try {
      // Use the field-based endpoint which auto-resolves country from GPS
      final regs = await _vaccineService.getFieldRegulations(_selectedFieldId!, species: _selectedType);
      setState(() {
        _regulations = regs;
        for (var reg in _regulations) {
          final vCode = reg.vaccine?.code ?? reg.vaccineId;
          if (!_vaccineSelections.containsKey(vCode)) {
            _vaccineSelections[vCode] = {
              'checked': false,
              'date': DateFormat('yyyy-MM-dd').format(DateTime.now()),
              'dose': 1.0,
              'lot': '',
              'isOther': false,
              'name': reg.vaccine?.nameFr ?? reg.vaccine?.nameEn ?? reg.vaccineId,
            };
          }
        }

        // Fix #4 — pré-cocher les vaccins déjà administrés en mode édition
        if (isEditMode && widget.animal?.vaccineRecords != null) {
          for (final record in widget.animal!.vaccineRecords!) {
            final code = record.vaccine?.code ?? record.vaccineId;
            if (_vaccineSelections.containsKey(code)) {
              _vaccineSelections[code]!['checked'] = true;
              _vaccineSelections[code]!['date'] =
                  record.administeredAt.toIso8601String().split('T')[0];
              _vaccineSelections[code]!['dose'] = record.doseGiven;
            } else {
              // Vaccin existant non présent dans les réglementations → ajouter comme "OTHER"
              final otherId = 'OTHER_${record.id}';
              _vaccineSelections[otherId] = {
                'checked': true,
                'date': record.administeredAt.toIso8601String().split('T')[0],
                'dose': record.doseGiven,
                'lot': record.lotNumber ?? '',
                'isOther': true,
                'name': (record.vaccine?.code == 'OTHER' ? record.notes : record.vaccine?.nameFr)
                    ?? record.notes
                    ?? 'Vaccin',
              };
            }
          }
        }
      });
    } catch (_) {
      // Silently fail — regulations will be empty
    } finally {
      setState(() => _isLoadingRegulations = false);
    }
  }

  @override
  void dispose() {
    // All TextEditingControllers must be disposed to avoid memory leaks
    _nameController.dispose();
